(function() {
	var Realmac = Realmac || {};

	Realmac.meta = {
		
		// Set the browser title
		//
		// @var String text
		setTitle: function(text) {
			return document.title = text;
		},
		
		// Set the content attribute of a meta tag
		//
		// @var String name
		// @var String content
		setTagContent: function(tag, content){
			// If the tag being set is title
			// return the result of setTitle
			if ( tag === 'title' )
			{
				return this.setTitle(content);
			}
			
			// Otherwise try and find the meta tag
			var tag = this.getTag(tag);
			
			// If we have a tag, set the content
			if ( tag !== false )
			{
				return tag.setAttribute('content', content);
			}
			
			return false;
		},
		
		// Find a meta tag
		//
		// @var String name
		getTag: function(name) {
			var meta = document.querySelectorAll('meta');
			
			for ( var i=0; i<meta.length; i++ )
			{
				if (meta[i].name == name){
					return meta[i];
				}
			}
			
			var tag = document.createElement('meta');
			tag.name = name;
			document.getElementsByTagName('head')[0].appendChild(tag);
			
			return tag;
		}
	};
 
	// Object containing all website meta info
	var websiteMeta = {"linux-setup-prerequisites.html":"(valid for version 1.1.x)\n\nSikuliX internally uses OpenCV to support the image related features and Tesseract for the text features. \n\nRead here about","category-latestnews.html":"A list of posts in category &ldquo;LatestNews&rdquo;","tag-offline.html":"Posts tagged &ldquo;Offline&rdquo;","c77aee9efb9985e68684cf70bbaa21a9-3.html":"If internal downloads are blocked on your system, you might try an Offline Setup.\n","category-ide.html":"A list of posts in category &ldquo;IDE&rdquo;","tag-linux.html":"Posts tagged &ldquo;Linux&rdquo;","category-setup.html":"A list of posts in category &ldquo;Setup&rdquo;"};
 
	// pageId must match the key in websiteMeta object
	var url = window.location.pathname;
	var pageId = url.substring(url.lastIndexOf('/')+1);
	if (!pageId || pageId.length == 0){
		pageId = 'index.html';
	}
	pageMeta = websiteMeta[pageId];
 
	// If we have meta for this page
	if (pageMeta){
		Realmac.meta.setTagContent('description', pageMeta);
	}
 
 })();